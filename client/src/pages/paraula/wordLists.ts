// ─── Valid guess word sets (answers are always valid guesses too) ─────────────
// We use the answer list as the valid guess list for simplicity
// (a larger dictionary would be used in production)
export const CA_VALID = new Set(CA_ANSWERS.map(stripAccents));
export const ES_VALID = new Set(ES_ANSWERS.map(stripAccents));
export const EN_VALID = new Set(EN_ANSWERS.map(stripAccents));

export type GameLang = "ca" | "es" | "en";

export function getAnswerList(lang: GameLang): string[] {
  if (lang === "ca") return CA_ANSWERS;
  if (lang === "es") return ES_ANSWERS;
  return EN_ANSWERS;
}

export function getValidSet(lang: GameLang): Set<string> {
  if (lang === "ca") return CA_VALID;
  if (lang === "es") return ES_VALID;
  return EN_VALID;
}

/** Get today's answer word seeded by date (same for everyone on the same day) */
export function getDailyWord(lang: GameLang): string {
  const list = getAnswerList(lang);
  const epoch = new Date("2024-01-01").getTime();
  const today = new Date();
  const dayIndex = Math.floor((today.getTime() - epoch) / 86400000);
  return list[((dayIndex % list.length) + list.length) % list.length];
}
